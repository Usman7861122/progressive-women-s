"""
Turns the hero heading into clean SVG outlines (Manrope SemiBold, overlaps merged).
Dev-time only. The result is saved in src/data/heading-paths.ts, so builds never need Python.

Run again only if you change the heading text:
    pip install fonttools brotli uharfbuzz skia-pathops
    python3 scripts/generate_heading_paths.py
"""
import io, json, pathlib
import uharfbuzz as hb
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen

ROOT = pathlib.Path(__file__).resolve().parent.parent
FONT = ROOT / "node_modules/@fontsource/manrope/files/manrope-latin-600-normal.woff2"

SIZE, PAD = 100.0, 10.0
ASCENT, LINE_H = SIZE * 0.78, SIZE * 1.12

tt = TTFont(str(FONT))
tt.flavor = None
from fontTools.ttLib.removeOverlaps import removeOverlaps
removeOverlaps(tt)  # merge overlapping contours so the outline has no stray lines
buf = io.BytesIO(); tt.save(buf)
hb_font = hb.Font(hb.Face(buf.getvalue()))
order = tt.getGlyphOrder()
gs = tt.getGlyphSet()
scale = SIZE / tt["head"].unitsPerEm
fmt = lambda v: ("%.2f" % v).rstrip("0").rstrip(".")

def shape(line):
    b = hb.Buffer(); b.add_str(line); b.guess_segment_properties()
    hb.shape(hb_font, b, {"kern": True, "liga": False})
    return b.glyph_infos, b.glyph_positions

def layout(lines):
    shaped = [shape(l) for l in lines]
    widths = [sum(p.x_advance for p in pos) * scale for _, pos in shaped]
    width = int(max(widths) + PAD * 2 + 0.999)
    height = int(LINE_H * (len(lines) - 1) + SIZE * 1.18 + PAD * 2 + 0.999)
    glyphs = []
    for li, (infos, pos) in enumerate(shaped):
        x = (width - widths[li]) / 2
        y = PAD + ASCENT + li * LINE_H
        for info, p in zip(infos, pos):
            pen = SVGPathPen(gs, ntos=fmt)
            gs[order[info.codepoint]].draw(TransformPen(pen, (scale, 0, 0, -scale, x + p.x_offset * scale, y)))
            d = pen.getCommands()
            if d: glyphs.append(d)
            x += p.x_advance * scale
    return {"width": width, "height": height, "glyphs": glyphs}

single = ["Compassionate care."]
stacked = ["Compassionate", "care."]
out = (
    "// AUTO-GENERATED by scripts/generate_heading_paths.py. Do not edit by hand.\n"
    f"export const headingText = {json.dumps(' '.join(single))};\n"
    f"export const headingSingle = {json.dumps(layout(single))};\n"
    f"export const headingStacked = {json.dumps(layout(stacked))};\n"
)
(ROOT / "src/data/heading-paths.ts").write_text(out)
print("written", len(out), "bytes")
